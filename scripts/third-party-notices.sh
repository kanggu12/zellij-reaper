#!/bin/sh
# Write THIRD_PARTY_NOTICES.md: the license of every module compiled into
# zellij-reaper, and of Go itself, which the release archives and packages
# carry next to the binary. Run it after changing dependencies:
#
#   make notices
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT INT TERM

# Only what is linked into the binary is distributed with it, not every module
# go.mod names, so the list comes from the binary itself.
CGO_ENABLED=0 go build -trimpath -o "$tmp/zellij-reaper" ./cmd/zellij-reaper
go version -m "$tmp/zellij-reaper" | awk '$1 == "dep" { print $2, $3 }' >"$tmp/deps"

# license_file prints the license file of the module in directory $1.
license_file() {
  for name in LICENSE LICENSE.txt LICENSE.md COPYING LICENCE; do
    if [ -f "$1/$name" ]; then
      echo "$1/$name"
      return 0
    fi
  done
  return 1
}

# kind names the license in file $1 from words every copy of it carries.
kind() {
  if grep -q "Apache License" "$1"; then
    echo "Apache-2.0"
  elif grep -q "Permission is hereby granted, free of charge" "$1"; then
    echo "MIT"
  elif grep -q "Neither the name" "$1"; then
    echo "BSD-3-Clause"
  elif grep -q "Redistribution and use in source and binary forms" "$1"; then
    echo "BSD-2-Clause"
  else
    echo "see the text below"
  fi
}

out="$tmp/notices.md"
{
  echo "# Third-party notices"
  echo
  echo "zellij-reaper is MIT-licensed (see [LICENSE](LICENSE)). Its binary is built from the Go modules below and the Go"
  echo "standard library; their licenses follow. This file is generated by \`scripts/third-party-notices.sh\`."
  echo
  echo "| Module | Version | License |"
  echo "|:---|:---:|:---:|"
  while read -r mod ver; do
    dir=$(go list -m -f '{{.Dir}}' "$mod")
    # A module without a license file must not go unnoticed.
    file=$(license_file "$dir") || { echo "no license file in $mod" >&2; exit 1; }
    echo "| \`$mod\` | $ver | $(kind "$file") |"
  done <"$tmp/deps"
  echo "| Go standard library | | $(kind "$(go env GOROOT)/LICENSE") |"
  echo
  echo "The lettering of the logo in \`docs/assets\` is drawn from JetBrains Mono, licensed under the SIL Open Font"
  echo "License 1.1."
  while read -r mod ver; do
    dir=$(go list -m -f '{{.Dir}}' "$mod")
    file=$(license_file "$dir")
    echo
    echo "## $mod $ver"
    echo
    echo '```text'
    cat "$file"
    echo '```'
  done <"$tmp/deps"
  echo
  echo "## Go standard library"
  echo
  echo '```text'
  cat "$(go env GOROOT)/LICENSE"
  echo '```'
} >"$out"
mv "$out" THIRD_PARTY_NOTICES.md
echo "wrote THIRD_PARTY_NOTICES.md ($(wc -l <"$tmp/deps" | tr -d ' ') modules)"
